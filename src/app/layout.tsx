/**
 * Sets a flag on <html> before first paint.
 *
 * The scroll-reveal animation hides its content with CSS scoped to
 * `html[data-js]`. Without this flag nothing is ever hidden, so a visitor with
 * no JavaScript — or one whose bundle failed — reads the page as plain,
 * fully visible content. The previous GSAP implementation did the opposite:
 * it painted every section at opacity 0 and relied on a script to bring it
 * back.
 */
const JS_FLAG = `document.documentElement.setAttribute('data-js','')`;

export default function RootLayout({
  children,
}: {
  children: React.ReactNode;
}) {
  return (
    <html
      lang="en-GB"
      className={`${inter.variable} ${poppins.variable} h-full antialiased`}
    >
      <head>
        <script dangerouslySetInnerHTML={{ __html: JS_FLAG }} />
      </head>
      <body className="flex min-h-full flex-col bg-white font-sans text-gray-900">
        {/* First thing in the tab order on every page. */}
        <a
          href="#main"
          className="sr-only focus:not-sr-only focus:fixed focus:left-4 focus:top-4 focus:z-[100] focus:rounded-full focus:bg-green-600 focus:px-5 focus:py-3 focus:font-semibold focus:text-white"
        >
          Skip to main content
        </a>

        {/* The company and the website, declared once for the whole site.
            Individual pages add only what is true of them specifically. */}
        <SiteJsonLd />

        {children}
      </body>
    </html>
  );
}
